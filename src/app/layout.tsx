import type { Metadata, Viewport } from "next";
import { GeistSans } from "geist/font/sans";
import { GeistMono } from "geist/font/mono";
import { MotionProvider } from "@/components/layout/MotionProvider";
import { siteConfig, sameAsLinks } from "@/data/site";
import "./globals.css";

// Fonts are self-hosted via the `geist` package: no external requests, better LCP and privacy.

const fullTitle = `${siteConfig.name} | ${siteConfig.title}`;

export const metadata: Metadata = {
  metadataBase: new URL(siteConfig.url),
  title: {
    default: fullTitle,
    template: `%s | ${siteConfig.name}`,
  },
  description: siteConfig.description,
  keywords: [...siteConfig.keywords],
  authors: [{ name: siteConfig.name, url: siteConfig.url }],
  creator: siteConfig.name,
  alternates: { canonical: "/" },
  openGraph: {
    type: "website",
    url: siteConfig.url,
    siteName: fullTitle,
    title: fullTitle,
    description: siteConfig.description,
    locale: siteConfig.locale,
  },
  twitter: {
    card: "summary_large_image",
    title: fullTitle,
    description: siteConfig.description,
  },
  robots: {
    index: true,
    follow: true,
    googleBot: { index: true, follow: true, "max-image-preview": "large", "max-snippet": -1 },
  },
  // Add after verifying in Google Search Console:
  // verification: { google: "your-token" },
};

export const viewport: Viewport = {
  themeColor: "#050505",
  colorScheme: "dark",
  width: "device-width",
  initialScale: 1,
};

// Structured data helps search engines understand who the site is about.
const jsonLd = {
  "@context": "https://schema.org",
  "@graph": [
    {
      "@type": "WebSite",
      "@id": `${siteConfig.url}/#website`,
      url: siteConfig.url,
      name: fullTitle,
      description: siteConfig.description,
      inLanguage: "en",
    },
    {
      "@type": "Person",
      "@id": `${siteConfig.url}/#person`,
      name: siteConfig.name,
      jobTitle: siteConfig.title,
      url: siteConfig.url,
      description: siteConfig.description,
      knowsAbout: [
        "Web development",
        "Next.js",
        "React",
        "TypeScript",
        "Software testing",
        "Quality assurance",
      ],
      ...(sameAsLinks.length > 0 ? { sameAs: sameAsLinks } : {}),
      ...(siteConfig.location ? { homeLocation: { "@type": "Place", name: siteConfig.location } } : {}),
    },
  ],
};

// LayoutProps is generated by Next and includes the @modal parallel-route slot.
export default function RootLayout({ children, modal }: LayoutProps<"/">) {
  return (
    <html
      lang="en"
      className={`${GeistSans.variable} ${GeistMono.variable} antialiased`}
    >
      <body className="min-h-dvh">
        <a href="#main" className="skip-link">
          Skip to main content
        </a>
        <MotionProvider>
          {children}
          {modal}
        </MotionProvider>
        {/* Without JavaScript, entrance animations would leave content invisible. Show everything. */}
        <noscript>
          <style>{`[style*="opacity: 0"],[style*="opacity:0"]{opacity:1!important}[style*="translateY"],[style*="transform"]{transform:none!important}`}</style>
        </noscript>
        <script
          type="application/ld+json"
          // JSON.stringify output is safe; "<" is escaped to prevent script injection.
          dangerouslySetInnerHTML={{ __html: JSON.stringify(jsonLd).replace(/</g, "\\u003c") }}
        />
      </body>
    </html>
  );
}
